// Minimal i18n: en (default) + zh-TW, no library. localStorage keeps the
// choice on this device.
import { ref } from 'vue';
import { PRODUCT } from './productConfig.js';

export const SUPPORTED_LANGS = ['en', 'zh-TW'];

function normalizeLang(l) {
  return SUPPORTED_LANGS.includes(l) ? l : 'en';
}

export const lang = ref(normalizeLang(localStorage.getItem(PRODUCT.storageKeys.language) || 'en'));
// Dates and times follow the app's language: 10:04 AM in English, 上午 10:04 in Chinese.
export const timeLocale = () => (lang.value === 'en' ? 'en-US' : 'zh-TW');

export function setLang(l, { persist = true } = {}) {
  const next = normalizeLang(l);
  lang.value = next;
  if (persist) localStorage.setItem(PRODUCT.storageKeys.language, next);
}

