// {product} in a text is the product's name (productConfig.js), so the account and
// settings texts need no product name of their own.
// Nothing (null, undefined) is nothing, not the words "null" or "undefined".
export function ct(text) { if (text == null) return ''; return String(lang.value === 'zh-TW' ? text : (english[text] ?? text)).replaceAll('{product}', PRODUCT.name); }
export function duration(seconds) {
  const zh = lang.value === 'zh-TW';
  if (seconds < 60) return zh ? `${seconds} 秒` : `${seconds}s`;
  const m = Math.floor(seconds / 60), s = seconds % 60;
  return zh ? (s ? `${m} 分 ${s} 秒` : `${m} 分`) : (s ? `${m}m ${s}s` : `${m}m`);
}
// The one line under the navbar while an agent is working: what it is doing, how
// many tools this answer has taken, and how long the current step has run.
export function progressLine({tool, tools, seconds, total}) {
  const zh = lang.value === 'zh-TW';
  const parts = [tool || (zh ? '思考中' : 'Thinking')];
  if (tools > 0) parts.push(zh ? `本輪第 ${tools} 個工具` : `step ${tools}`);
  if (seconds !== null && seconds !== undefined) parts.push(duration(seconds));
  if (total !== null && total !== undefined && total > (seconds ?? -1)) parts.push(zh ? `本輪共 ${duration(total)}` : `turn ${duration(total)}`);
  return parts.join(' · ');
}
// Work still running in the background after the turn that started it: subagents
// working on their own and commands sent to the background. One subagent is named
// by its task, one command by what it runs; the time is the longest-running.
export function backgroundLine({subagents, commands, task, command = '', seconds}) {
  const zh = lang.value === 'zh-TW';
  const parts = [];
  if (subagents > 0) parts.push(zh ? `${subagents} 個 subagent 工作中${subagents === 1 && task ? `（${task}）` : ''}`
    : `${subagents} subagent${subagents === 1 ? '' : 's'} working${subagents === 1 && task ? ` (${task})` : ''}`);
  if (commands > 0) parts.push(zh ? `${commands} 個背景指令執行中${commands === 1 && command ? `（${command}）` : ''}`
    : `${commands} background command${commands === 1 ? '' : 's'} running${commands === 1 && command ? ` (${command})` : ''}`);
  if (!parts.length) return '';
  const line = (zh ? '背景：' : 'Background: ') + parts.join(zh ? '、' : ', ');
  return seconds !== null && seconds !== undefined ? line + ' · ' + duration(seconds) : line;
}
